"""Deterministic RDKit feature extraction, without an invented risk model."""

import base64
from datetime import UTC, datetime
from typing import Literal

from pydantic import BaseModel
from rdkit import Chem, rdBase
from rdkit.Chem import Descriptors, rdMolDescriptors
from rdkit.Chem.Draw import rdMolDraw2D

from .evidence import BY_ID, Evidence
from .rules import RULES, RULESET_VERSION, DraftRule


class Match(BaseModel):
    rule: DraftRule
    atom_matches: list[list[int]]
    count: int


class ScreeningResult(BaseModel):
    canonical_smiles: str
    molecular_formula: str
    molecular_weight: float
    formal_charge: int
    atom_count: int
    matches: list[Match]
    formulation_context: tuple[Evidence, ...] = (BY_ID["EVONIK-H2O2-STABILITY"],)
    depiction: str
    engine: str
    ruleset_version: str
    analyzed_at: str
    risk_status: Literal["not_assessed"] = "not_assessed"
    validated_rule_count: Literal[0] = 0
    message: str


PATTERNS = [(rule, Chem.MolFromSmarts(rule.smarts)) for rule in RULES]
if any(pattern is None for _, pattern in PATTERNS):
    raise RuntimeError("Invalid bundled SMARTS pattern")


def screen(smiles: str) -> ScreeningResult:
    if not 1 <= len(smiles) <= 2000 or any(c.isspace() for c in smiles):
        raise ValueError("SMILES harus 1-2000 karakter tanpa spasi atau nama tambahan.")
    params = Chem.SmilesParserParams()
    params.allowCXSMILES = False
    params.parseName = False
    with rdBase.BlockLogs():
        molecule = Chem.MolFromSmiles(smiles, params)
    if molecule is None or not molecule.GetNumAtoms():
        raise ValueError("SMILES tidak valid atau valensi atom tidak dapat disanitasi.")
    if molecule.GetNumAtoms() > 200:
        raise ValueError("Maksimum 200 atom per molekul untuk penapisan interaktif.")
    if len(Chem.GetMolFrags(molecule)) != 1:
        raise ValueError("Masukkan satu molekul. Campuran atau komposisi rahasia belum didukung.")
    if any(atom.GetAtomicNum() == 0 for atom in molecule.GetAtoms()):
        raise ValueError("Atom wildcard tidak menggambarkan struktur molekul yang pasti.")
    # Discard atom-map labels so images contain only chemistry generated by RDKit.
    for atom in molecule.GetAtoms():
        atom.SetAtomMapNum(0)
    matches = []
    highlights: set[int] = set()
    for rule, pattern in PATTERNS:
        indices = molecule.GetSubstructMatches(pattern, uniquify=True, maxMatches=1000)
        if indices:
            matches.append(
                Match(rule=rule, atom_matches=[list(x) for x in indices], count=len(indices))
            )
            highlights.update(i for match in indices for i in match)
    drawing = rdMolDraw2D.MolDraw2DSVG(520, 300)
    drawing.DrawMolecule(molecule, highlightAtoms=sorted(highlights))
    drawing.FinishDrawing()
    svg = base64.b64encode(drawing.GetDrawingText().encode()).decode()
    return ScreeningResult(
        canonical_smiles=Chem.MolToSmiles(molecule, isomericSmiles=True),
        molecular_formula=rdMolDescriptors.CalcMolFormula(molecule),
        molecular_weight=round(Descriptors.MolWt(molecule), 4),
        formal_charge=Chem.GetFormalCharge(molecule),
        atom_count=molecule.GetNumAtoms(),
        matches=matches,
        depiction="data:image/svg+xml;base64," + svg,
        engine="RDKit " + rdBase.rdkitVersion,
        ruleset_version=RULESET_VERSION,
        analyzed_at=datetime.now(UTC).isoformat(),
        message=(
            "Gugus dihitung dari struktur input. Semua aturan masih draft. "
            "Tidak adanya kecocokan bukan bukti aman, stabil, atau efektif antimikroba. "
            "pH, suhu, konsentrasi, logam jejak, dan interaksi campuran belum dievaluasi."
        ),
    )
